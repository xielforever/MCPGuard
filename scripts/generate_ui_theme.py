#!/usr/bin/env python3
"""Generate shared runtime theme data from the approved UI/UX numeric sources."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / 'design-system/mcpguard/tokens.json'
LABELS = ROOT / 'design-system/mcpguard/state-labels.json'
DESTINATION = ROOT / 'internal/uitheme'


def kebab(value):
    return re.sub(r'(?<!^)([A-Z])', r'-\1', value).lower()


def get(value, path):
    for part in path.split('.'):
        value = value[part]
    return value


def resolve(value, tokens, seen=()):
    if isinstance(value, str) and re.fullmatch(r'\{[^{}]+\}', value):
        path = value[1:-1]
        if path in seen:
            raise ValueError('Cyclic UI token')
        return resolve(get(tokens, path), tokens, seen + (path,))
    return value


def generate():
    tokens = json.loads(TOKENS.read_text(encoding='utf-8'))
    labels = json.loads(LABELS.read_text(encoding='utf-8'))
    if tokens['theme'] != 'starship-d':
        raise ValueError('The runtime console requires the selected D theme')
    fingerprint = hashlib.sha256(TOKENS.read_bytes() + LABELS.read_bytes()).hexdigest()
    variables = []

    def add(name, value, unit=''):
        value = resolve(value, tokens)
        variables.append(f'  --mg-{name}: {value}{unit if isinstance(value, (int, float)) else ""};')

    for name, value in tokens['semantic']['color'].items():
        add('color-' + kebab(name), value)
    for name, value in tokens['semantic']['shadow'].items():
        add('shadow-' + kebab(name), value)
    add('scrim', tokens['semantic']['scrim'])
    for category, unit in [('space', 'px'), ('radius', 'px'), ('stroke', 'px')]:
        for name, value in tokens['primitives'][category].items():
            add(category + '-' + kebab(name), value, unit)
    add('font-family-body', tokens['typography']['bodyFamily'])
    add('font-family-mono', tokens['typography']['monoFamily'])
    for name, values in tokens['typography']['scale'].items():
        add('font-size-' + kebab(name), values['size'], 'px')
        add('line-height-' + kebab(name), values['lineHeight'], 'px')
        add('font-weight-' + kebab(name), values['weight'])
    add('font-size-mobile-input', tokens['typography']['mobileInputSize'], 'px')
    for name, value in tokens['layout'].items():
        if isinstance(value, (int, float)):
            add('layout-' + kebab(name), value, 'px')
    for name, value in tokens['layout']['zIndex'].items():
        add('z-index-' + kebab(name), value)
    for component, values in tokens['components'].items():
        for name, value in values.items():
            add(kebab(component) + '-' + kebab(name), value, 'px')
    for name in ['hover', 'enter', 'exit', 'orbit']:
        add('motion-' + name, tokens['motion'][name], 'ms')
    add('easing-enter', tokens['motion']['easingEnter'])
    add('easing-exit', tokens['motion']['easingExit'])
    css = '\n'.join([
        '/* Generated by scripts/generate_ui_theme.py; edit tokens.json, not this file. */',
        f'/* UI/UX {tokens["version"]}; source SHA-256 {fingerprint} */',
        ':root {', '  color-scheme: dark;', *variables, '}', ''
    ])
    data = json.dumps(labels['labelSets'], ensure_ascii=False, separators=(',', ':'))
    javascript = '\n'.join([
        "'use strict';",
        '// Generated by scripts/generate_ui_theme.py; edit state-labels.json.',
        f'// UI/UX {tokens["version"]}; source SHA-256 {fingerprint}',
        '(() => {',
        '  const freeze = value => { Object.values(value).forEach(v => { if (v && typeof v === "object") freeze(v); }); return Object.freeze(value); };',
        '  globalThis.MCPGuardUIStateLabels = freeze(' + data + ');',
        '})();', ''
    ])
    return {'tokens.generated.css': css, 'state-labels.generated.js': javascript}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    stale = []
    for name, content in output.items():
        path = DESTINATION / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode('utf-8'):
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode('utf-8'))
    if stale:
        raise SystemExit('Shared UI theme is stale: ' + ', '.join(stale))
    print('Shared D theme: ' + ('checked' if args.check else 'generated') + ' (2 files).')


if __name__ == '__main__':
    main()
