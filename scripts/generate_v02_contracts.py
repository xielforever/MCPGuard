#!/usr/bin/env python3
"""Generate v0.2 contract copies, Go DTOs and OpenAPI. Never connects to services."""
import argparse, copy, json, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "internal/contracts/v02/source.json"

def go_name(value):
    words = re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?=[A-Z]|$)|[0-9]+", value)
    initialisms = {"id", "url", "sql", "tls", "uuid", "rpc", "mcp"}
    return "".join(w.upper() if w.lower() in initialisms else w[:1].upper() + w[1:] for w in words)

def go_type(spec):
    if "$ref" in spec: return spec["$ref"].rsplit("/", 1)[-1]
    return {"string": "string", "boolean": "bool", "integer": "int"}.get(spec.get("type"), "") or ("[]" + go_type(spec["items"]) if spec.get("type") == "array" else struct_type(spec))

def struct_type(spec):
    required = spec.get("required", [])
    lines = ["struct {"]
    for key, val in spec["properties"].items():
        kind = go_type(val)
        optional = key not in required
        if optional and not kind.startswith("[]"): kind = "*" + kind
        tag = key + (",omitempty" if optional else "")
        lines.append("    " + go_name(key) + " " + kind + ' `json:"' + tag + '"`')
    return "\n".join(lines + ["}"])

def refs(value):
    if isinstance(value, dict): return {k: (v.replace("#/$defs/", "#/components/schemas/") if k == "$ref" else refs(v)) for k, v in value.items()}
    if isinstance(value, list): return [refs(x) for x in value]
    return value

def outputs(source):
    public = {k: v for k, v in source.items() if not k.startswith("x-")}
    code = ["// Code generated by scripts/generate_v02_contracts.py; DO NOT EDIT.", "package v02", ""]
    code.append('const ContractRevision = ' + json.dumps(source.get('x-contract-revision', '0.2.0')))
    for key, value in source["x-limits"].items(): code.append("const " + go_name(key) + " = " + str(value))
    for name, spec in source["$defs"].items():
        alias = " = " if spec.get("type") in ("string", "boolean", "integer") else " "
        code.append("type " + name + alias + go_type(spec) + "\n")
    formatted = subprocess.run(["gofmt"], input="\n".join(code).encode(), stdout=subprocess.PIPE, check=True).stdout
    api = {"openapi": "3.1.0", "info": {"title": "MCPGuard resource access", "version": "0.2.0"}, "servers": [{"url": "/api/v2"}], "paths": {}, "components": {"securitySchemes": {"employee": {"type": "http", "scheme": "bearer"}}, "schemas": refs(copy.deepcopy(source["$defs"]))}, "security": [{"employee": []}]}
    api['info']['version'] = source.get('x-contract-revision', '0.2.0')
    api['components']['securitySchemes']['browser'] = {'type':'apiKey','in':'cookie','name':'mcpguard_console'}
    api['components']['securitySchemes']['delivery'] = {'type':'apiKey','in':'header','name':'X-MCPGuard-Delivery-Token','description':'Private credential:claim authorization, audience mcpguard-delivery; requires current employee authentication as well. Never sent to MCP.'}
    api['components']['securitySchemes']['context'] = {'type':'apiKey','in':'header','name':'X-MCPGuard-Credential-Context','description':'Private enrolled-client context proof, always combined with current employee authentication. Never a model argument.'}
    for op in source["x-http-operations"]:
        item = {"operationId": op["operationId"], "x-implementation-stage": op["stage"], "responses": {"200": {"description": "Authorized result", "content": {"application/octet-stream" if op.get("binary") else "application/json": {"schema": {"type": "string", "format": "binary"} if op.get("binary") else {"$ref": "#/components/schemas/" + op["output"]}}}}, "400": {"description": "Invalid request"}, "403": {"description": "Access denied"}, "503": {"description": "Required authority unavailable"}}}
        item["responses"]["401"] = {"description": "Current employee authentication required"}
        item['responses']['409'] = {'description':'Revision or idempotency conflict'}
        if op.get('privateDelivery'):
            item['security'] = [{'employee':[], 'delivery':[]}]
            item['x-delivery-mode'] = 'MANUAL_OWNER'
        if op.get('privateContext'):
            item['security'] = [{'employee':[], 'context':[]}]
        if op.get('binary'):
            item['responses']['200']['headers'] = {name:{'schema':{'type':'string'}} for name in ('Content-Disposition','Cache-Control','X-MCPGuard-Package-SHA256')}
        if op.get('browser'):
            item['servers'] = [{'url':'/console/api/v2'}]
            item['security'] = [{'browser':[]}]
            if op['method'] != 'get':
                item['parameters'] = [{'in':'header','name':name,'required':True,'schema':{'type':'string'}} for name in ('Origin','X-CSRF-Token','If-Match','Idempotency-Key')]
        if "{id}" in op["path"]: item.setdefault('parameters',[]).append({"name": "id", "in": "path", "required": True, "schema": {"$ref": "#/components/schemas/UUID"}})
        if op.get("input") and op["method"] == "get":
            schema = source["$defs"][op["input"]]
            item.setdefault("parameters", []).extend({"name": k, "in": "query", "required": k in schema["required"], "schema": refs(v)} for k, v in schema["properties"].items())
        elif op.get("input"): item["requestBody"] = {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/" + op["input"]}}}}
        api["paths"].setdefault(op["path"], {})[op["method"]] = item
    encode = lambda x: (json.dumps(x, ensure_ascii=False, indent=2) + "\n").encode()
    return {ROOT / "internal/contracts/v02/types_generated.go": formatted,
            ROOT / "docs/specs/v0.2/contract.schema.json": encode(public),
            ROOT / "docs/specs/v0.2/openapi.json": encode(api),
            ROOT / "docs/specs/v0.2/examples.json": encode(source["x-examples"]),
            ROOT / "docs/specs/v0.2/mcp-tools.json": encode(source["x-mcp-tools"])}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = outputs(json.loads(SOURCE.read_text()))
    stale = []
    for path, content in expected.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale: raise SystemExit("Stale generated contracts: " + ", ".join(stale))
    print("v0.2 generated contracts " + ("verified" if args.check else "written") + ": " + str(len(expected)))

if __name__ == "__main__": main()

